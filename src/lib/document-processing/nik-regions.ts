/**
 * Decodes NIK 6-digit prefix into Provinsi and Kota/Kabupaten
 */
export function decodeNikRegion(nik: string): { province?: string; city?: string } {
  if (!nik || nik.length < 4) return {};
  const provCode = nik.substring(0, 2);
  const kabCode = nik.substring(0, 4);

  const province = PROVINCE_MAP[provCode];
  const city = KABUPATEN_MAP[kabCode];

  return { province, city };
}
